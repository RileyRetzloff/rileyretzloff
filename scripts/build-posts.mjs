// posts/*.md -> src/app/blog/posts.generated.ts (gitignored). Runs before
// `npm start`, `npm run build` and `npm test`; to publish a post, add a
// markdown file with `title` and `date` frontmatter to posts/.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { marked } from "marked";
import frontmatter from "../api/_lib/frontmatter.js";

const POSTS_DIR = new URL("../posts/", import.meta.url);
const OUT_FILE = new URL("../src/app/blog/posts.generated.ts", import.meta.url);

const files = (await readdir(POSTS_DIR)).filter((file) => file.endsWith(".md"));
const posts = await Promise.all(
  files.map(async (file) => {
    const { data, body } = frontmatter.parse(await readFile(new URL(file, POSTS_DIR), "utf8"));
    const slug = file.slice(0, -3);
    // marked passes inline HTML through, so posts can mix in raw HTML.
    return { slug, title: data.title || slug, date: data.date || "", html: await marked.parse(body) };
  }),
);
posts.sort((a, b) => b.date.localeCompare(a.date));

await writeFile(
  OUT_FILE,
  `// Generated by scripts/build-posts.mjs from posts/*.md. Do not edit.
import type { Post } from "./post";

export const POSTS: Post[] = ${JSON.stringify(posts, null, 2)};
`,
);
console.log(`build-posts: ${posts.length} post(s)`);
