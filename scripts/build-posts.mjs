// Builds src/app/blog/posts.generated.ts from posts/*.md.
// Runs automatically via the `prebuild` / `prestart` npm hooks —
// you never need to run it by hand. Just add a markdown file to
// posts/ with frontmatter (title, date) and push.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { marked } from "marked";

const ROOT = new URL("../", import.meta.url);
const POSTS_DIR = new URL("posts/", ROOT);
const OUT_FILE = new URL("src/app/blog/posts.generated.ts", ROOT);

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) return { data: {}, body: raw };
  const data = {};
  for (const line of match[1].split(/\r?\n/)) {
    const i = line.indexOf(":");
    if (i > 0) data[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { data, body: match[2] };
}

const files = (await readdir(POSTS_DIR)).filter((f) => f.endsWith(".md")).sort();
const posts = [];

for (const file of files) {
  const raw = await readFile(new URL(file, POSTS_DIR), "utf8");
  const { data, body } = parseFrontmatter(raw);
  const slug = path.basename(file, ".md");
  // marked passes inline HTML straight through, so posts can mix
  // markdown and raw HTML (colors, embeds, whatever) freely.
  const html = await marked.parse(body);
  posts.push({
    slug,
    title: data.title || slug,
    date: data.date || "",
    html,
  });
}

posts.sort((a, b) => (b.date || "").localeCompare(a.date || ""));

const ts = `// AUTO-GENERATED by scripts/build-posts.mjs — do not edit by hand.
export interface BlogPost {
  slug: string;
  title: string;
  date: string;
  /** Rendered HTML. The author's own content, committed to this repo. */
  html: string;
}

export const POSTS: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`;

await mkdir(new URL("src/app/blog/", ROOT), { recursive: true });
await writeFile(OUT_FILE, ts);
console.log(`build-posts: ${posts.length} post(s) -> src/app/blog/posts.generated.ts`);
