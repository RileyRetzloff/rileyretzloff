// Writes src/environments/environment.generated.ts (gitignored) from env
// vars, so the frontend and the /api functions always use the same Clerk
// instance: whatever CLERK_PUBLISHABLE_KEY says. On Vercel that's the value
// for the deployment's environment (Production, Preview); locally it's
// .env.local.
import { mkdir, writeFile } from "node:fs/promises";

try {
  process.loadEnvFile(new URL("../.env.local", import.meta.url));
} catch {
  // No .env.local; rely on the real environment.
}

const key = process.env.CLERK_PUBLISHABLE_KEY ?? "";
if (!key) {
  const message = "build-env: CLERK_PUBLISHABLE_KEY isn't set (see .env.example)";
  // A deployment without it would silently ship a site where sign-in is broken.
  if (process.env.VERCEL) throw new Error(message);
  console.warn(`${message}; sign-in won't work.`);
}

const dir = new URL("../src/environments/", import.meta.url);
await mkdir(dir, { recursive: true });
await writeFile(
  new URL("environment.generated.ts", dir),
  `// Generated by scripts/build-env.mjs from env vars. Do not edit.
export const environment = {
  clerkPublishableKey: ${JSON.stringify(key)},
};
`,
);
if (key) console.log(`build-env: Clerk ${key.startsWith("pk_live_") ? "production" : "development"} instance`);
